def _p(feature: Feature, name: str) -> str:
    return f'P["{feature.id}.{name}"]'


def _flange_frame(edge: str) -> dict[str, Any]:
    """Unit normal and tangent of a base edge, as source expressions."""
    return {
        "+y": {"n": (0, 1), "t": (1, 0), "half": "W / 2", "run": "L"},
        "-y": {"n": (0, -1), "t": (1, 0), "half": "W / 2", "run": "L"},
        "+x": {"n": (1, 0), "t": (0, 1), "half": "L / 2", "run": "W"},
        "-x": {"n": (-1, 0), "t": (0, 1), "half": "L / 2", "run": "W"},
    }[edge]


def _axis(tangent: int, normal: int) -> str:
    """One coordinate of a point on a flange: along the edge (u) or through it (inner)."""
    if tangent:
        return "u"
    return {1: "inner", -1: "-inner", 0: "0"}[normal]


def free_corners(tree: FeatureTree) -> list[tuple[int, int]]:
    """Signs (sx, sy) of the base corners a fillet applies to."""
    corners = [(-1, -1), (1, -1), (1, 1), (-1, 1)]
    fillets = tree.of_type("fillet")
    if not fillets:
        return []
    if fillets[0].params["corners"] == "all":
        return corners
    for flange in tree.of_type("flange"):
        nx, ny = _flange_frame(flange.params["edge"])["n"]
        corners = [c for c in corners if not (nx and c[0] == nx) and not (ny and c[1] == ny)]
    return corners


def generate_cadquery(tree: FeatureTree) -> str:
    """Return the full source of ``model.py`` for a validated feature tree."""
    tree.validate()
    base = tree.base
    out: list[str] = [_HEADER]
    w = lambda line="": out.append(("    " + line if line else "") + "\n")  # noqa: E731

    w(f"L, W, T = {_p(base, 'length')}, {_p(base, 'width')}, {_p(base, 'thickness')}")
    w()
    w(f"# {base.id}: base plate, centred on the origin, sitting on Z = 0")
    w('part = cq.Workplane("XY").box(L, W, T, centered=(True, True, False))')

    for fillet in tree.of_type("fillet"):
        corners = free_corners(tree)
        w()
        w(f"# {fillet.id}: rounded plate corners ({fillet.params['corners']})")
        w(f"r = {_p(fillet, 'radius')}")
        w(f"for sx, sy in {corners}:")
        w("    cx, cy = sx * L / 2, sy * W / 2")
        w("    corner = cq.selectors.BoxSelector((cx - 0.1, cy - 0.1, -0.1), (cx + 0.1, cy + 0.1, T + 0.1))")
        w("    part = part.edges(corner).fillet(r)")

    for flange in tree.of_type("flange"):
        fr = _flange_frame(flange.params["edge"])
        (nx, ny), half = fr["n"], fr["half"]
        w()
        w(f"# {flange.id}: flange standing on the {flange.params['edge']} edge (height from Z = 0)")
        w(f"fh, ft = {_p(flange, 'height')}, {_p(flange, 'thickness')}")
        size = "L, ft, fh" if ny else "ft, W, fh"
        shift = f"{'-' if nx + ny < 0 else ''}({half} - ft / 2)"
        offset = f"({shift}, 0, 0)" if nx else f"(0, {shift}, 0)"
        w(f'part = part.union(cq.Workplane("XY").box({size}, centered=(True, True, False)).translate({offset}))')

    for boss in tree.of_type("boss"):
        w()
        w(f"# {boss.id}: round boss on top of the base")
        w(
            f"part = part.union(cq.Solid.makeCylinder({_p(boss, 'diameter')} / 2, {_p(boss, 'height')}, "
            f"cq.Vector({_p(boss, 'x')}, {_p(boss, 'y')}, T), cq.Vector(0, 0, 1)))"
        )

    for boss in tree.of_type("boss"):
        if boss.params.get("bore", 0) > 0:
            w(f"# {boss.id}: bore through the boss and the base")
            w(
                f"part = part.cut(cq.Solid.makeCylinder({_p(boss, 'bore')} / 2, T + {_p(boss, 'height')} + 2, "
                f"cq.Vector({_p(boss, 'x')}, {_p(boss, 'y')}, -1), cq.Vector(0, 0, 1)))"
            )

    for hole in tree.of_type("hole"):
        parent = tree.get(hole.parent) if hole.parent else base
        w()
        if parent.type == "flange":
            fr = _flange_frame(parent.params["edge"])
            (nx, ny), (tx, ty), half = fr["n"], fr["t"], fr["half"]
            ft = _p(parent, "thickness")
            w(f"# {hole.id}: through hole in {parent.id} (u along the edge, v above Z = 0)")
            w(f"u, v, inner = {_p(hole, 'u')}, {_p(hole, 'v')}, {half} - {ft} - 1")
            w(
                f"part = part.cut(cq.Solid.makeCylinder({_p(hole, 'diameter')} / 2, {ft} + 2, "
                f"cq.Vector({_axis(tx, nx)}, {_axis(ty, ny)}, v), cq.Vector({nx}, {ny}, 0)))"
            )
        else:
            w(f"# {hole.id}: through hole in the base")
            w(
                f"part = part.cut(cq.Solid.makeCylinder({_p(hole, 'diameter')} / 2, T + 2, "
                f"cq.Vector({_p(hole, 'x')}, {_p(hole, 'y')}, -1), cq.Vector(0, 0, 1)))"
            )

    for slot in tree.of_type("slot"):
        w()
        w(f"# {slot.id}: through slot in the base (length is overall, end to end)")
        w(
            f'part = part.cut(cq.Workplane("XY").slot2D({_p(slot, "length")}, {_p(slot, "width")}, {_p(slot, "angle")})'
            f'.extrude(T + 2).translate(({_p(slot, "x")}, {_p(slot, "y")}, -1)))'
        )

    w()
    out.append(_FOOTER)
    return "".join(out)


def build(tree: FeatureTree, params: dict[str, float] | None = None):
    """Execute the generated source and return the CadQuery workplane."""
    namespace: dict[str, Any] = {"__file__": str(Path.cwd() / "model.py"), "__name__": "caliper_generated_model"}
    exec(compile(generate_cadquery(tree), "<caliper model>", "exec"), namespace)
    return namespace["build"](params if params is not None else tree.params())


def write_model(tree: FeatureTree, out_dir: str | Path) -> dict[str, Path]:
    """Write ``feature_tree.json``, ``params.json`` and ``model.py``."""
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    paths = {"tree": out / "feature_tree.json", "params": out / "params.json", "model": out / "model.py"}
    tree.save(paths["tree"])
    paths["params"].write_text(json.dumps(tree.params(), indent=2) + "\n", encoding="utf-8")
    paths["model"].write_text(generate_cadquery(tree), encoding="utf-8")
    return paths
